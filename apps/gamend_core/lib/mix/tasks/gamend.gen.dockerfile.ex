defmodule Mix.Tasks.Gamend.Gen.Dockerfile do
  @shortdoc "Writes the Dockerfile every app built on Gamend shares"

  @moduledoc """
  Writes `Dockerfile` from Gamend's one template, filled in from the app's
  own `mix.exs`, so Gamend, the starter and every host build the same way.

      mix gamend.gen.dockerfile          # write Dockerfile
      mix gamend.gen.dockerfile --check  # fail if it is out of date
      mix gamend.gen.dockerfile -o PATH  # write somewhere else

  What differs between apps comes from the project, never from a hand edit:

    * the path dependencies inside the repository (an umbrella's `apps/*`, a
      plugin the host compiles as a dependency), whose `mix.exs` the
      dependency layer needs before the rest of the source;
    * the config read at compile time: every `config/*.exs` but
      `runtime.exs` and `host_runtime.exs`, read at boot, so an edit to them
      does not compile every dependency again;
    * the release: the one `releases:` names, or the app's own.

  And from `gamend_dockerfile:` in the project, all optional:

      gamend_dockerfile: [
        db_adapter: "postgres",                  # default "sqlite"
        plugins_dir: "modules/plugins_examples", # default "modules/plugins"
        build_args: ["ENGINE_TAG=nightly"]       # ARGs the asset step reads
      ]

  A build step of the app's own (fetching an engine build, the docs) goes in
  its `assets.deploy` alias. A new `SYNC` build arg runs that step again
  (`deploy.conf`'s `BUILD_ARGS`), so whatever it fetches is fresh on every
  deploy without rebuilding the dependencies.
  """

  use Mix.Task

  # Read at boot, never at compile time: copying them into the dependency
  # layer would compile every dependency again on each edit.
  @runtime_config ~w(runtime.exs host_runtime.exs)

  @impl true
  def run(argv) do
    {opts, _rest} =
      OptionParser.parse!(argv, strict: [check: :boolean, output: :string], aliases: [o: :output])

    path = Keyword.get(opts, :output, "Dockerfile")
    generated = render(project_inputs())

    if Keyword.get(opts, :check, false) do
      check(path, generated)
    else
      File.write!(path, generated)
      Mix.shell().info("wrote #{path}")
    end
  end

  defp check(path, generated) do
    case File.read(path) do
      {:ok, ^generated} ->
        Mix.shell().info("#{path} is up to date")

      {:ok, _stale} ->
        Mix.raise("#{path} is out of date. Run: mix gamend.gen.dockerfile")

      {:error, _reason} ->
        Mix.raise("#{path} does not exist. Run: mix gamend.gen.dockerfile")
    end
  end

  defp project_inputs do
    config = Mix.Project.config()
    opts = Keyword.get(config, :gamend_dockerfile, [])
    app = Keyword.fetch!(config, :app)
    releases = Keyword.get(config, :releases, [])

    %{
      app: app,
      release: release_name(app, releases),
      named_release?: releases != [],
      db_adapter: Keyword.get(opts, :db_adapter, "sqlite"),
      plugins_dir: Keyword.get(opts, :plugins_dir, "modules/plugins"),
      build_args: Keyword.get(opts, :build_args, []),
      path_deps: local_path_deps(Keyword.get(config, :deps, [])),
      config_files: compile_time_config()
    }
  end

  defp release_name(app, []), do: app
  defp release_name(_app, [{name, _opts} | _]), do: name

  # A path inside the repository; a sibling checkout (`../gamend`) is not in
  # the build context, and the app's mix.exs resolves it from Hex there.
  defp local_path_deps(deps) do
    deps
    |> Enum.flat_map(fn
      {_app, opts} when is_list(opts) -> List.wrap(opts[:path])
      {_app, _req, opts} when is_list(opts) -> List.wrap(opts[:path])
      _other -> []
    end)
    |> Enum.map(&Path.relative_to_cwd(Path.expand(&1)))
    |> Enum.reject(&(Path.type(&1) == :absolute or String.starts_with?(&1, "..")))
    |> Enum.uniq()
    |> Enum.sort()
  end

  defp compile_time_config do
    "config/*.exs"
    |> Path.wildcard()
    |> Enum.reject(&(Path.basename(&1) in @runtime_config))
    |> Enum.sort()
  end

  @doc false
  # Public so a test can render one without a project.
  @spec render(map()) :: String.t()
  def render(inputs) do
    """
    # syntax=docker/dockerfile:1
    # Generated by `mix gamend.gen.dockerfile`: Gamend's one Dockerfile, filled
    # in from this app's mix.exs. Do not edit; change `gamend_dockerfile:` there
    # and run it again (`--check` fails on a file that drifted).
    #
    #   docker build .                    an OTP release on gamend-runtime, ~11x smaller
    #   docker build --target full .      the builder, running `mix phx.server`
    #
    # The system packages, Rust, Hex and the start scripts are the base images
    # (gamend's docker/README.md). Build args: GAMEND_DB_ADAPTER (a compile-time
    # choice, so an image is one adapter's), MIX_ENV, RELEASE,
    # GAMEND_CONTENT_APP_VERSION, and SYNC, whose new value runs the asset step
    # again.

    ARG BUILDER_IMAGE=ghcr.io/appsinacup/gamend-builder:elixir-1.20
    ARG RUNNER_IMAGE=ghcr.io/appsinacup/gamend-runtime:trixie
    ARG MIX_ENV=prod
    ARG RELEASE=#{inputs.release}
    ARG GAMEND_DB_ADAPTER=#{inputs.db_adapter}
    ARG GAMEND_CONTENT_PLUGINS_DIR=#{inputs.plugins_dir}
    ARG GAMEND_CONTENT_APP_VERSION=1.0.0

    # ── Builder ───────────────────────────────────────────────────────────────
    FROM ${BUILDER_IMAGE} AS builder

    ARG MIX_ENV
    ARG GAMEND_DB_ADAPTER
    ARG GAMEND_CONTENT_PLUGINS_DIR
    ENV MIX_ENV=${MIX_ENV} \\
        GAMEND_DB_ADAPTER=${GAMEND_DB_ADAPTER} \\
        GAMEND_CONTENT_PLUGINS_DIR=${GAMEND_CONTENT_PLUGINS_DIR}

    # The dependencies in layers of their own, keyed on what resolves and
    # compiles them, so a source change rebuilds the app and not ~140
    # dependencies and their NIFs. Path dependencies arrive with the source.
    #{dependency_copies(inputs)}RUN mix deps.get

    # A precompiled NIF GitHub will not serve (a 504, an outage) fails the first
    # pass; the second builds what is left from source, with the builder's Rust.
    #{config_copy(inputs.config_files)}RUN mix deps.compile --skip-local-deps || \\
        RUSTLER_PRECOMPILED_FORCE_BUILD_ALL=1 mix deps.compile --skip-local-deps

    # The lock as deps.get left it. Beside a gamend checkout Gamend's packages
    # are path dependencies, so an app's committed lock has none of them; the
    # source brings that lock back, and deps.get would add and compile them anew.
    RUN cp mix.lock /tmp/mix.lock.resolved

    COPY . .
    RUN cp /tmp/mix.lock.resolved mix.lock && mix deps.get
    RUN mix compile

    # The plugins in GAMEND_CONTENT_PLUGINS_DIR, each bundled; one the app
    # compiles as a path dependency was built just now and is skipped.
    RUN gamend-build-plugins --verbose

    # The app's own build steps live in its `assets.deploy` alias.
    ARG SYNC=0
    #{build_arg_lines(inputs.build_args)}RUN echo "sync ${SYNC}" && \\
        if [ "$MIX_ENV" = prod ]; then \\
          mix assets.deploy && gamend-copy-static #{inputs.app} --require; \\
        else \\
          mix assets.build; \\
        fi

    # Last: it changes on every commit, and an ARG invalidates every layer after
    # it. Never during deps.compile, where Gamend's Hex packages would read it
    # as their own version.
    ARG GAMEND_CONTENT_APP_VERSION
    ENV GAMEND_CONTENT_APP_VERSION=${GAMEND_CONTENT_APP_VERSION}

    # ── Full ──────────────────────────────────────────────────────────────────
    FROM builder AS full
    EXPOSE 4000 443
    CMD ["gamend-start"]

    # ── Release (default target) ──────────────────────────────────────────────
    # Last, so a bare `docker build .` builds it: what a host such as Gamend
    # Cloud runs, `bin/<release>` in the working directory.
    FROM builder AS release-build
    ARG RELEASE
    # The release, with what it reads from its working directory beside it
    # (theme, content, docs, plugins) and what it declares
    # (`gamend-metadata.json`): one directory for the runtime to take.
    RUN #{release_command(inputs)} && gamend-stage-release "${RELEASE}"

    FROM ${RUNNER_IMAGE} AS release
    ARG MIX_ENV
    ARG RELEASE
    ARG GAMEND_DB_ADAPTER
    ARG GAMEND_CONTENT_PLUGINS_DIR
    ARG GAMEND_CONTENT_APP_VERSION
    # The adapter is read again at boot and must agree with the compiled one.
    ENV GAMEND_RELEASE=${RELEASE} \\
        GAMEND_DB_ADAPTER=${GAMEND_DB_ADAPTER} \\
        GAMEND_CONTENT_PLUGINS_DIR=${GAMEND_CONTENT_PLUGINS_DIR} \\
        GAMEND_CONTENT_APP_VERSION=${GAMEND_CONTENT_APP_VERSION}
    COPY --from=release-build /app/_build/${MIX_ENV}/rel/${RELEASE} ./
    EXPOSE 4000 443
    CMD ["sh", "-c", "exec gamend-release-start \\"$GAMEND_RELEASE\\""]
    """
  end

  defp dependency_copies(inputs) do
    Enum.map_join(
      ["COPY mix.exs mix.lock ./" | Enum.map(inputs.path_deps, &"COPY #{&1}/mix.exs #{&1}/")],
      &(&1 <> "\n")
    )
  end

  defp config_copy([]), do: ""
  defp config_copy(files), do: "COPY #{Enum.join(files, " ")} config/\n"

  defp build_arg_lines(args), do: Enum.map_join(args, &"ARG #{&1}\n")

  # `mix release NAME` finds only a release `releases:` names; with none, the
  # bare form assembles the one named after the app.
  defp release_command(%{named_release?: true}), do: ~s(mix release "${RELEASE}" --overwrite)
  defp release_command(_inputs), do: "mix release --overwrite"
end
