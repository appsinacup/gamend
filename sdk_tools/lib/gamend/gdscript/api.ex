  @spec contexts() :: [String.t()]
  def contexts, do: @table |> Map.keys() |> Enum.sort()

  @doc "Function names on `context`, or `nil` when the context is unknown."
  @spec functions(String.t()) :: [String.t()] | nil
  def functions(context) do
    case Map.fetch(@table, context) do
      {:ok, functions} -> functions |> Map.keys() |> Enum.sort()
      :error -> nil
    end
  end

  @doc "Arities `context.function` accepts, or `nil` when it does not exist."
  @spec arities(String.t(), String.t()) :: [non_neg_integer()] | nil
  def arities(context, function) do
    with {:ok, functions} <- Map.fetch(@table, context),
         {:ok, arities} <- Map.fetch(functions, function) do
      arities
    else
      :error -> nil
    end
  end
